"""Generate the new PSRM tables from archived confidence-set results.

Only the three named reporting table files are regenerated. Archived numerical
results and all pre-existing manuscript tables are read-only inputs.
"""
from __future__ import annotations

import csv
from decimal import Decimal, ROUND_CEILING, ROUND_FLOOR
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "output/reports/confidence_sets_2026-11-08"
FRESH = ROOT / "output/experiments/fixed_h_score_validation_2026-11-08/summary"
FIXED = ROOT / "output/experiments/disconnected_sets_2026-11-08/fixed_variance"
OUT = ROOT / "paper/tables"
AUDIT = ROOT / "output/psrm_reporting_update_2026-11-08"
METHODS = ("Calibrated WGAN-DML", "Empirical-local DML", "Smooth plug-in")
LABELS = {"Calibrated WGAN-DML": "Calibrated GAN",
          "Empirical-local DML": "Empirical DML",
          "Smooth plug-in": "Smooth plug-in"}
ROW_END = " " + chr(92) * 2


def read_rows(path):
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def outward(value, lower):
    return format(Decimal(str(value)).quantize(Decimal("0.0001"),
                  rounding=ROUND_FLOOR if lower else ROUND_CEILING), ".4f")


def interval_text(left, right):
    return "[" + outward(left, True) + "," + outward(right, False) + "]"


def main():
    input_paths = [REPORT / "summary.csv", REPORT / "flagged_cases.csv",
                   FRESH / "summary.csv", FIXED / "summary.csv"]
    before = {str(p.relative_to(ROOT)): sha(p) for p in input_paths}
    reported = read_rows(input_paths[0])
    flags = read_rows(input_paths[1])
    fresh = read_rows(input_paths[2])
    fixed = read_rows(input_paths[3])
    rindex = {(int(r["auctions"]), r["method"], r["reported_object"]): r for r in reported}
    findex = {(int(r["auctions"]), r["method"], r["interval"]): r for r in fresh}
    sindex = {(int(r["auctions"]), r["method"], r["interval"]): r for r in fixed}
    if len(rindex) != 18 or len(findex) != 12 or len(sindex) != 18:
        raise ValueError("Unexpected or duplicated summary rows")

    lines = ["% Generated by code/build_psrm_reporting_tables.py; do not edit numbers.",
             r"{\small", r"\setlength{\tabcolsep}{4pt}",
             r"\begin{tabular}{rlrrrrrr}", r"\toprule",
             r"& & \multicolumn{2}{c}{Coverage (\%)} & \multicolumn{3}{c}{Mean length} & Counts" + ROW_END,
             r"\cmidrule(lr){3-4}\cmidrule(lr){5-7}",
             r"$n$ & Method & Wald & Full set & Wald & Full set & Envelope & F/D/B" + ROW_END,
             r"\midrule"]
    numerical_rows = []
    for n in (500, 2000):
        for method in METHODS:
            w = findex[n, method, "Wald"]
            s = rindex[n, method, "Full score set"]
            e = rindex[n, method, "Conservative envelope"]
            # Same completed experiment, two independent summary exports.
            saved_score = findex[n, method, "Score inversion"]
            if abs(float(saved_score["coverage"]) - float(s["coverage"])) > 1e-12:
                raise AssertionError("Coverage exports disagree")
            if abs(float(saved_score["mean_length"]) - float(s["mean_length"])) > 1e-12:
                raise AssertionError("Length exports disagree")
            if abs(float(e["coverage"]) - float(s["coverage"])) > 1e-12:
                raise AssertionError("Envelope coverage needs a separate column for these data")
            if int(s["repetitions"]) != 100 or int(w["repetitions"]) != 100:
                raise AssertionError("Not 100 repetitions")
            fcount = int(s["failure_count"])
            dcount = int(s["disconnected_count"])
            bcount = int(s["lower_boundary_count"]) + int(s["upper_boundary_count"])
            fields = [f"{n:,}", LABELS[method], f"{100*float(w['coverage']):.0f}",
                      f"{100*float(s['coverage']):.0f}", f"{float(w['mean_length']):.5f}",
                      f"{float(s['mean_length']):.5f}", f"{float(e['mean_length']):.5f}",
                      f"{fcount}/{dcount}/{bcount}"]
            lines.append(" & ".join(fields) + ROW_END)
            numerical_rows.append(dict(auctions=n, method=method, wald_coverage=float(w["coverage"]),
                score_coverage=float(s["coverage"]), wald_length=float(w["mean_length"]),
                score_length=float(s["mean_length"]), envelope_length=float(e["mean_length"]),
                failures=fcount, disconnected=dcount, boundary=bcount))
        if n == 500:
            lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}", "}",
              "% F/D/B: failed intervals / disconnected full sets / full sets touching a search boundary.",
              "% Coverage denominator is all 100 repetitions; lengths condition on successful intervals."]
    (OUT / "fresh_score_validation.tex").write_text("\n".join(lines) + "\n")

    flag_lines = ["% Endpoints are rounded outward to four decimals for display only.",
                  r"{\small", r"\setlength{\tabcolsep}{3pt}",
                  r"\begin{tabular}{rlll}", r"\toprule",
                  r"Replication & Method & Full confidence set & Conservative envelope" + ROW_END,
                  r"\midrule"]
    flag_details = []
    flags.sort(key=lambda r: (int(r["repetition"]), METHODS.index(r["method"])))
    for row in flags:
        components = json.loads(row["score_components"])
        text = "$" + r"\,\cup\,".join(interval_text(a,b) for a,b in components) + "$"
        low = float(row["conservative_hull_lower"])
        high = float(row["conservative_hull_upper"])
        if low > min(a for a,b in components) or high < max(b for a,b in components):
            raise AssertionError("Envelope does not contain the original set")
        if any(Decimal(outward(a,True)) > Decimal(str(a)) or
               Decimal(outward(b,False)) < Decimal(str(b)) for a,b in components):
            raise AssertionError("Display rounding is not outward")
        flag_lines.append(" & ".join([row["repetition"], LABELS[row["method"]], text,
                          "$"+interval_text(low,high)+"$"]) + ROW_END)
        flag_details.append(dict(repetition=int(row["repetition"]),method=row["method"],
                                components=components,envelope=[low,high]))
    if len(flags) != 4:
        raise AssertionError("Unexpected flagged row count")
    flag_lines += [r"\bottomrule", r"\end{tabular}", "}"]
    (OUT / "confidence_set_flagged.tex").write_text("\n".join(flag_lines) + "\n")

    sens_lines = ["% Exploratory re-use of the fresh validation samples; not independent confirmation.",
                  r"{\small", r"\setlength{\tabcolsep}{4pt}",
                  r"\begin{tabular}{rlrrrrr}", r"\toprule",
                  r"& & \multicolumn{3}{c}{Coverage (\%)} & \multicolumn{2}{c}{Mean length}"+ROW_END,
                  r"\cmidrule(lr){3-5}\cmidrule(lr){6-7}",
                  r"$n$ & Method & Wald & Full set & Fixed scale & Full set & Fixed scale"+ROW_END,
                  r"\midrule"]
    sens_rows=[]
    for n in (500,2000):
        for method in METHODS:
            w=sindex[n,method,"Wald"];s=sindex[n,method,"Original score"];f=sindex[n,method,"Fixed variance score"]
            sens_lines.append(" & ".join([f"{n:,}",LABELS[method],f"{100*float(w['coverage']):.0f}",
                f"{100*float(s['coverage']):.0f}",f"{100*float(f['coverage']):.0f}",
                f"{float(s['mean_length']):.5f}",f"{float(f['mean_length']):.5f}"])+ROW_END)
            sens_rows.append(dict(auctions=n,method=method,fixed_coverage=float(f["coverage"]),
                fixed_length=float(f["mean_length"]),disconnected=int(f["disconnected_sets"]),
                failures=int(f["failures"])))
        if n==500:sens_lines.append(r"\addlinespace")
    sens_lines += [r"\bottomrule",r"\end{tabular}","}",
                   "% The fixed-scale variant is a sensitivity exercise, not the adopted reporting rule."]
    (OUT / "score_set_sensitivity.tex").write_text("\n".join(sens_lines)+"\n")

    AUDIT.mkdir(parents=True,exist_ok=True)
    unchanged = all(sha(ROOT/k)==v for k,v in before.items())
    record=dict(passed=unchanged,source_sha256=before,source_unchanged=unchanged,
        table_rows=dict(fresh_score_validation=6,confidence_set_flagged=4,score_set_sensitivity=6),
        endpoint_display_rule="outward rounding to four decimals; original machine-precision endpoints unchanged",
        main_table=numerical_rows,flagged=flag_details,sensitivity=sens_rows,
        table_sha256={name:sha(OUT/name) for name in ("fresh_score_validation.tex",
                        "confidence_set_flagged.tex","score_set_sensitivity.tex")})
    (AUDIT/"table_generation_checks.json").write_text(json.dumps(record,indent=2)+"\n")
    if not unchanged:raise AssertionError("Source data changed")
    print("Generated 3 new tables; 6 main rows, 4 flagged rows, 6 sensitivity rows; sources unchanged.")


if __name__=="__main__":main()
